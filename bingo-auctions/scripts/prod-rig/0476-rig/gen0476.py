"""Generate 0476 (+ rollback) from the LIVE prod body of _find_lot_by_scan.
usage: python3 gen0476.py <prod.sql> <migration out> <rollback out>"""
import sys
src, mig_out, rb_out = sys.argv[1:4]
body = open(src).read().rstrip('\n')
assert body.startswith('CREATE OR REPLACE FUNCTION public._find_lot_by_scan(p_candidates text[])')
LIVE_MD5 = '6a40bb40390d5c812534d791b778fa8a'

old = """       (EXISTS (
          SELECT 1 FROM public.invoice_lots il
           WHERE il.lot_id = cur.id
             AND il.refunded_at IS NULL
             AND il.forfeited_at IS NULL
             AND il.picked_up_at IS NULL
        )) DESC,"""
new = """       (EXISTS (
          SELECT 1 FROM public.invoice_lots il
            JOIN public.invoices iv ON iv.id = il.invoice_id
           WHERE il.lot_id = cur.id
             AND il.refunded_at IS NULL
             AND il.forfeited_at IS NULL
             AND il.picked_up_at IS NULL
             -- 0476: only a sale that is still alive. A declined-and-relisted
             -- (or canceled) invoice left an "open" line on the OLD row, so a
             -- scan of TEA4842561 hopped back to BIN-031301 and the iPad named
             -- that row's declined buyer.
             AND iv.status IN ('pending', 'paid', 'partially_refunded', 'payment_failed_grace')
        )) DESC,"""
assert body.count(old) == 1, 'live body changed: the open-line ranking block was not found exactly once'
fixed = body.replace(old, new)

HEADER = """-- ============================================================================
-- Migration 0476 — the sticker scan resolver ignores dead sales when it picks
-- the current row of a relist chain.
--
-- Why (read-only prod check, 2026-10-28, TEA4842561): scanning the sticker on
-- the iPad named the OLD buyer ("winner KERRENE"). _find_lot_by_scan walks the
-- relist chain and prefers the row with an open invoice line (not refunded,
-- not forfeited, not picked up). The old row BIN-031301 still has a line on
-- its declined invoice (status payment_failed_relisted, never refunded), and
-- the current row's line was refunded on 10-26, so the scan hopped back to
-- the old row; staff_scan_lot_owner then reported that row's declined buyer.
--
-- Change: one condition. The "open line" must sit on an invoice that is
-- still a sale (pending, paid, partially_refunded, payment_failed_grace).
-- Everything else in the body is the live prod body, byte for byte
-- (generated by scripts/prod-rig/0476-rig/gen0476.py; the preflight below
-- refuses if the live body is not the one this was generated from).
--
-- Callers that change behaviour: every sticker/lot-code scan that resolves
-- through _find_lot_by_scan (put-away, lot lookup, checkout scan,
-- staff_scan_lot_owner, relot). Only chains where an older row holds a dead
-- invoice line resolve differently, now to the newest live row.
--
-- LOCKS / WINDOW: CREATE OR REPLACE FUNCTION only (catalog lock, no table
-- lock). Any hour outside 18:00-22:00 CT. ACL unchanged (CREATE OR REPLACE
-- keeps it).
-- Rollback: scripts/prod-rig/0476_ROLLBACK_scan_resolver_ignores_dead_sales.sql
-- ============================================================================

BEGIN;
SET LOCAL lock_timeout = '3s';

DO $pre$
DECLARE v_md5 TEXT;
BEGIN
  SELECT md5(pg_get_functiondef('public._find_lot_by_scan(text[])'::regprocedure)) INTO v_md5;
  -- The live body (what this was generated from), or 0476 itself (re-apply).
  IF v_md5 IS DISTINCT FROM '%s' AND v_md5 IS DISTINCT FROM '%s' THEN
    RAISE EXCEPTION '0476: _find_lot_by_scan live body is not the one this migration was generated from (md5 %%). Regenerate; nothing changed.', v_md5;
  END IF;
END
$pre$;

"""
# md5 of the fixed functiondef is computed on the rig and pasted in by run.sh's
# first apply; to keep the file self-contained we accept both by a placeholder
# filled below.
fixed_md5 = '@@FIXED_MD5@@'
# Prod ACL is explicit grants (postgres, anon, authenticated, service_role) and
# no PUBLIC entry, so this REVOKE changes nothing; it is here for the
# function-grants lint. The explicit grants are kept as they are.
REVOKE = "\n\nREVOKE EXECUTE ON FUNCTION public._find_lot_by_scan(text[]) FROM PUBLIC;"
mig = HEADER % (LIVE_MD5, fixed_md5) + fixed + ';' + REVOKE + '\n\nCOMMIT;\n'
rb = """-- Rollback for 0476: restore the exact live body of _find_lot_by_scan from
-- before 0476 (generated by gen0476.py from the prod body). Catalog lock only.
BEGIN;
SET LOCAL lock_timeout = '3s';

""" + body + ';\n\nCOMMIT;\n'
open(mig_out, 'w').write(mig)
open(rb_out, 'w').write(rb)
print('ok')
