-- relist chain and prefers the row with an open invoice line (not refunded,
-- not forfeited, not picked up). The old row BIN-031301 still has a line on
-- its declined invoice (status payment_failed_relisted, never refunded), and
-- the current row's line was refunded on 10-26, so the scan hopped back to
-- the old row; staff_scan_lot_owner then reported that row's declined buyer.
--
-- Change: one condition. The "open line" must sit on an invoice that is
-- still a sale (pending, paid, partially_refunded, payment_failed_grace).
