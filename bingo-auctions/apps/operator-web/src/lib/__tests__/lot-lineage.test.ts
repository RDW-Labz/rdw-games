// Regression cover for the 2026-07-30 "one lot, two states" field report.
//
// Lot PNK4858852 existed twice on prod: a `relisted` ancestor keeping the old
// lot_code + old bin, and the live child carrying `sticker_code=BIN:PNK4858852`
// in a different aisle. Every by-code lookup that matched `lot_code` exactly
// landed on the ancestor, so the console said "not in auction yet" and pointed
// staff at a bin the item had left — while the storefront showed the same code
// live with a countdown.

import { describe, expect, it } from 'vitest';
import type { SupabaseClient } from '@supabase/supabase-js';
import { findLotsByAnyCode, loadSuccessorChain, isRetiredLot } from '../lot-lineage';

type Row = {
  id: string;
  lot_code: string | null;
  sticker_code: string | null;
  status: string;
  created_at: string | null;
  relisted_from_lot_id?: string | null;
  deleted_at?: string | null;
  /** Generated by the DB (mig 0362), never written by hand — see withGenerated. */
  sticker_raw_upper?: string | null;
};

/**
 * Mirror of `lots.sticker_raw_upper` (mig 0362):
 *
 *     GENERATED ALWAYS AS (nullif(upper(split_part(sticker_code, ':', 2)), ''))
 *
 * Applied to every fixture on the way into the stub rather than written into
 * the fixtures themselves, so a new test case cannot forget it and quietly
 * assert that the sticker lookup is broken.
 */
function withGenerated(row: Row): Row {
  const raw = (row.sticker_code ?? '').split(':')[1] ?? '';
  return { ...row, sticker_raw_upper: raw === '' ? null : raw.toUpperCase() };
}

interface Recorded {
  or?: string;
  eq?: [string, unknown];
  isNull?: string;
  limit?: number;
}

/**
 * Minimal PostgREST-shaped stub: chainable, thenable, and it records the
 * filters so the tests can assert on the query we build (the `or` grammar is
 * the part that has to be exactly right) as well as on the rows we return.
 */
function fakeSupabase(rows: Row[]): { client: SupabaseClient; queries: Recorded[] } {
  const queries: Recorded[] = [];

  const makeBuilder = () => {
    const rec: Recorded = {};
    queries.push(rec);
    const builder: Record<string, unknown> = {
      select: () => builder,
      or: (v: string) => {
        rec.or = v;
        return builder;
      },
      eq: (col: string, val: unknown) => {
        rec.eq = [col, val];
        return builder;
      },
      is: (col: string) => {
        rec.isNull = col;
        return builder;
      },
      limit: (n: number) => {
        rec.limit = n;
        return builder;
      },
      then: (resolve: (r: { data: Row[] }) => unknown) => {
        const live = rows.map(withGenerated).filter((r) => !r.deleted_at);
        const data = rec.eq
          ? live.filter((r) => (r as Record<string, unknown>)[rec.eq![0]] === rec.eq![1])
          : live.filter((r) => matchesOr(r, rec.or ?? ''));
        return Promise.resolve(resolve({ data }));
      },
    };
    return builder;
  };

  return {
    client: { from: () => makeBuilder() } as unknown as SupabaseClient,
    queries,
  };
}

/** Evaluate the subset of the PostgREST `or=(…)` grammar these helpers emit. */
function matchesOr(row: Row, or: string): boolean {
  if (!or) return false;
  return or.split(',').some((clause) => {
    const [col, op, ...rest] = clause.split('.');
    const value = String((row as Record<string, unknown>)[col!] ?? '');
    const operand = rest.join('.');
    if (op === 'eq') return value === operand;
    if (op === 'ilike') {
      const pattern = operand.replace(/[.*+?^${}()|[\]\\]/g, '\\$&').replace(/%/g, '.*');
      return new RegExp(`^${pattern}$`, 'i').test(value);
    }
    return false;
  });
}

const ancestor: Row = {
  id: 'a',
  lot_code: 'PNK4858852',
  sticker_code: null,
  status: 'relisted',
  created_at: '2026-05-25T03:27:37Z',
  relisted_from_lot_id: null,
};
const current: Row = {
  id: 'b',
  lot_code: 'BIN-001737',
  sticker_code: 'BIN:PNK4858852',
  status: 'live',
  created_at: '2026-07-13T15:21:05Z',
  relisted_from_lot_id: 'a',
};

describe('findLotsByAnyCode', () => {
  it('matches the printed sticker label, not just the canonical lot_code', async () => {
    const { client } = fakeSupabase([ancestor, current]);
    const found = await findLotsByAnyCode<Row>(client, 'PNK4858852', '*');
    // Both incarnations answer to the code the box carries.
    expect(found.map((r) => r.id).sort()).toEqual(['a', 'b']);
  });

  it('matches a canonical lot_code case-insensitively', async () => {
    const { client } = fakeSupabase([ancestor, current]);
    const found = await findLotsByAnyCode<Row>(client, 'bin-001737', '*');
    expect(found.map((r) => r.id)).toEqual(['b']);
  });

  it('excludes soft-deleted rows', async () => {
    const { client, queries } = fakeSupabase([{ ...current, deleted_at: '2026-07-20T00:00:00Z' }]);
    const found = await findLotsByAnyCode<Row>(client, 'PNK4858852', '*');
    expect(found).toEqual([]);
    expect(queries[0]!.isNull).toBe('deleted_at');
  });

  it('probes a code containing an underscore without a LIKE pattern', async () => {
    // `_` is a single-char LIKE wildcard and PostgREST offers no ESCAPE, so
    // the old pattern terms would have let PNK4858852_01 match PNK4858852X01
    // — and were dropped entirely for such codes, which cost them
    // case-insensitive matching. Equality has no wildcard semantics, so the
    // special case is gone: these codes are probed like any other.
    const { client, queries } = fakeSupabase([]);
    await findLotsByAnyCode<Row>(client, 'PNK4858852_01', '*');
    expect(queries[0]!.or).toBe(
      'lot_code.eq.PNK4858852_01,sticker_code.eq.PNK4858852_01,' +
        'legacy_lot_code.eq.PNK4858852_01,sticker_raw_upper.eq.PNK4858852_01',
    );
  });

  it('probes legacy_lot_code — 4,679 prod lots carry one', async () => {
    const { client, queries } = fakeSupabase([]);
    await findLotsByAnyCode<Row>(client, 'PNK4858852', '*');
    expect(queries[0]!.or).toContain('legacy_lot_code.eq.PNK4858852');
  });

  it('emits no LIKE pattern — an unindexable OR branch scans all of lots (0362)', async () => {
    // The 2026-09-19 outage: sticker_code.ilike.%:CODE forced a sequential
    // scan of the whole table on every public lot page view. Assert on the
    // query shape, because the cost is invisible to a stub that returns rows.
    const { client, queries } = fakeSupabase([]);
    for (const code of ['PNK4858852', 'pnk4858852', 'BIN-001737', 'PNK_01']) {
      await findLotsByAnyCode<Row>(client, code, '*');
    }
    for (const q of queries) {
      expect(q.or ?? '').not.toContain('like');
      expect(q.or ?? '').not.toContain('%');
    }
  });

  it('refuses codes that could break out of the or() grammar', async () => {
    const { client, queries } = fakeSupabase([ancestor]);
    for (const bad of ['PNK,4858852', 'a.b', 'x)y', '%', '', '   ']) {
      expect(await findLotsByAnyCode<Row>(client, bad, '*')).toEqual([]);
    }
    expect(queries).toHaveLength(0); // never reached the database
  });
});

describe('loadSuccessorChain', () => {
  it('walks forward from a retired ancestor to the current incarnation', async () => {
    const { client } = fakeSupabase([ancestor, current]);
    const chain = await loadSuccessorChain<Row>(client, 'a', '*');
    expect(chain.map((r) => r.id)).toEqual(['b']);
    expect(chain[chain.length - 1]!.status).toBe('live');
  });

  it('follows multiple relists in order, oldest first', async () => {
    const third: Row = {
      id: 'c',
      lot_code: 'BIN-002000',
      sticker_code: 'BIN:PNK4858852',
      status: 'live',
      created_at: '2026-08-01T00:00:00Z',
      relisted_from_lot_id: 'b',
    };
    const { client } = fakeSupabase([ancestor, { ...current, status: 'relisted' }, third]);
    const chain = await loadSuccessorChain<Row>(client, 'a', '*');
    expect(chain.map((r) => r.id)).toEqual(['b', 'c']);
  });

  it('prefers the active child when a source has several', async () => {
    // The one-active-child unique index only constrains draft/scheduled/live,
    // so a source that was relisted, canceled, and relisted again has siblings.
    const canceledSibling: Row = {
      id: 'x',
      lot_code: 'BIN-000999',
      sticker_code: null,
      status: 'canceled',
      created_at: '2026-09-01T00:00:00Z', // newer, but dead
      relisted_from_lot_id: 'a',
    };
    const { client } = fakeSupabase([ancestor, current, canceledSibling]);
    const chain = await loadSuccessorChain<Row>(client, 'a', '*');
    expect(chain.map((r) => r.id)).toEqual(['b']);
  });

  it('returns an empty chain for a lot that was never relisted', async () => {
    const { client } = fakeSupabase([ancestor, current]);
    expect(await loadSuccessorChain<Row>(client, 'b', '*')).toEqual([]);
  });

  it('stops instead of spinning on a cyclic lineage', async () => {
    const loopA: Row = { ...ancestor, status: 'relisted', relisted_from_lot_id: 'b' };
    const loopB: Row = { ...current, status: 'relisted', relisted_from_lot_id: 'a' };
    const chain = await loadSuccessorChain<Row>(fakeSupabase([loopA, loopB]).client, 'a', '*');
    expect(chain.map((r) => r.id)).toEqual(['b']);
  });

  it('honours the hop limit on a long chain', async () => {
    const rows: Row[] = [ancestor];
    for (let i = 0; i < 8; i++) {
      rows.push({
        id: `n${i}`,
        lot_code: `BIN-00${i}`,
        sticker_code: null,
        status: 'relisted',
        created_at: `2026-08-0${i + 1}T00:00:00Z`,
        relisted_from_lot_id: i === 0 ? 'a' : `n${i - 1}`,
      });
    }
    const chain = await loadSuccessorChain<Row>(fakeSupabase(rows).client, 'a', '*', 3);
    expect(chain.map((r) => r.id)).toEqual(['n0', 'n1', 'n2']);
  });
});

describe('isRetiredLot', () => {
  it('treats relisted / canceled / disposed rows as history', () => {
    expect(isRetiredLot('relisted')).toBe(true);
    expect(isRetiredLot('canceled')).toBe(true);
    expect(isRetiredLot('disposed')).toBe(true);
    expect(isRetiredLot('live')).toBe(false);
    expect(isRetiredLot('won')).toBe(false);
    expect(isRetiredLot(null)).toBe(false);
  });
});
