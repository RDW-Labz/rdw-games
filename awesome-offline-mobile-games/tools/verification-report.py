#!/usr/bin/env python3
"""Render evidence/verification.md from the machine-readable harness output.

The point is that the human-readable record cannot drift from the machine record:
it is generated from evidence/browser-report.json, which tests/browser.mjs writes
after actually launching Chromium and playing each title.

    python3 tools/verification-report.py
"""
import json
import os
import subprocess
import sys
from datetime import datetime, timezone

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REPORT = os.path.join(ROOT, "evidence", "browser-report.json")
OUT = os.path.join(ROOT, "evidence", "verification.md")


def run(cmd):
    try:
        out = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True, timeout=60)
        return (out.stdout + out.stderr).strip()
    except Exception as exc:  # noqa: BLE001
        return f"(could not run: {exc})"


def main():
    if not os.path.isfile(REPORT):
        print("no evidence/browser-report.json — run `node tests/browser.mjs` first", file=sys.stderr)
        return 2
    rep = json.load(open(REPORT))
    smoke = run(["node", "tests/smoke.mjs"])
    prov = run(["python3", "tools/ports-provenance.py", "--check"])
    vend = run(["node", "tests/vendor.mjs"])
    cat = json.load(open(os.path.join(ROOT, "catalog", "games.json")))
    by_id = {g["id"]: g for g in cat["games"]}

    lines = []
    lines.append("# Verification record\n")
    lines.append("Generated by `python3 tools/verification-report.py` from "
                 "`evidence/browser-report.json`. Regenerate after any change; do not hand-edit.\n")
    lines.append(f"- harness run: **{rep['at']}** (UTC)")
    lines.append(f"- base URL: `{rep['base']}`")
    lines.append(f"- result: **{rep['pass']}/{rep['total']} passed**\n")

    lines.append("## What the browser harness asserts, per title\n")
    lines.append("1. the page loads with no console error, exception, or failed request")
    lines.append("2. the canvas is not blank — at least 8 distinct sampled colours")
    lines.append("3. the pixels change after the scripted input (so the game is live, not a still)")
    lines.append("4. `window.__game.state()` returns a sane object with `started: true`")
    n_orig = sum(1 for g in cat["games"] if g.get("lane") == "forge")
    n_hyb = sum(1 for g in cat["games"] if g.get("lane") == "hybrid")
    words = {1: "one", 2: "two", 3: "three", 4: "four", 5: "five", 6: "six", 7: "seven"}
    lines.append(f"5. every browser title — the {words.get(n_orig, n_orig)} originals ('forge' lane) and the "
                 f"{words.get(n_hyb, n_hyb)} cross-hybrids — also loads and\n"
                 "   plays over `file://`, i.e. with no server at all\n"
                 "   (and the vendored sprites/audio are confirmed to come off plain files, not a cache)\n")

    lines.append("| title | lane | load | canvas colours (title → play) | pixels changed | state after input | shots |")
    lines.append("|---|---|---|---|---|---|---|")
    for r in rep["results"]:
        gid = r["id"].replace("(file://)", "")
        g = by_id.get(gid, {})
        t = r.get("title") or {}
        p = r.get("play") or {}
        state = r.get("state") or {}
        if r["id"] == "shell":
            c = r.get("counts") or {}
            bits = f"cards={c.get('total')}, ports={c.get('ports')}, originals={c.get('originals')}, hybrids={c.get('hybrids')}"
            lines.append(f"| **Arcade Shell (launcher)** | — | {'PASS' if r['ok'] else 'FAIL'} | — | yes "
                         f"(filters + sheet) | {bits} | `shell-http.png` |")
            continue
        bits = ", ".join(f"{k}={v}" for k, v in list(state.items())[:6]) if isinstance(state, dict) else "—"
        base = r["id"].replace("(file://)", "").replace("(no vendor)", "").strip()
        if "no vendor" in r["id"]:
            shots = f"`{base}-no-vendor-*.png`"
        elif "(file" in r["id"]:
            shots = f"`{base}-file-title.png`, `{base}-file-play.png`"
        else:
            shots = f"`{base}-http-title.png`, `{base}-http-play.png`"
        lines.append(
            f"| **{g.get('title', r['id'])}** | {g.get('lane', '—')} | "
            f"{'PASS' if r['ok'] else 'FAIL'} | {t.get('colors', '—')} → {p.get('colors', '—')} | "
            f"{'yes' if p.get('changed') else 'no'} | {bits} | {shots} |"
        )
    lines.append("")

    fails = [r for r in rep["results"] if not r["ok"]]
    if fails:
        lines.append("## Failures\n")
        for r in fails:
            lines.append(f"### {r['id']}\n")
            for p in r.get("problems", []):
                lines.append(f"- {p}")
            lines.append("")
    else:
        lines.append("No failures. Every title above was launched in headless Chromium at a "
                     "390×844 mobile viewport, driven through its own debug surface, and "
                     "screenshotted.\n")

    lines.append("## Static invariants (`node tests/smoke.mjs`)\n")
    lines.append("```")
    lines.append(smoke)
    lines.append("```\n")

    lines.append("## Port provenance (`python3 tools/ports-provenance.py --check`)\n")
    lines.append("```")
    lines.append(prov)
    lines.append("```\n")

    man_path = os.path.join(ROOT, "vendor", "MANIFEST.json")
    if os.path.isfile(man_path):
        man = json.load(open(man_path))
        lines.append("## Vendored upstream content (`node tests/vendor.mjs`)\n")
        lines.append("Every shipped title is built on real content taken out of the cloned repos: "
                     "ship hulls, sprites, audio, dungeon layouts and game-data tables, converted to "
                     "browser-loadable form by `tools/vendor.py`. Every file is pinned to an upstream "
                     "commit and verified by size and SHA-256 on every test run.\n")
        lines.append("| source | files | size | licence | pinned commit |")
        lines.append("|---|---|---|---|---|")
        for name, src in sorted(man["sources"].items()):
            lines.append(f"| [{name}]({src['url']}) | {src['files']} | {src['bytes'] / 1e6:.2f} MB | "
                         f"{src['license']} | `{src['commit'][:12]}` |")
        total_files = len(man["files"])
        total_bytes = sum(f["bytes"] for f in man["files"])
        lines.append(f"| **total** | **{total_files}** | **{total_bytes / 1e6:.2f} MB** | mixed — see "
                     f"`docs/LICENSING.md` | |")
        lines.append("")
        lines.append("```")
        lines.append(vend)
        lines.append("```\n")

    off_path = os.path.join(ROOT, "evidence", "offline-report.json")
    if os.path.isfile(off_path):
        off = json.load(open(off_path))
        lines.append("## Offline / PWA proof (`node tests/offline.mjs`)\n")
        lines.append(f"Network cut at the DevTools-protocol level after the service worker installed; "
                     f"**{off['pass']}/{off['total']}** checks passed at {off['at']} (UTC).\n")
        lines.append("| check | result | detail |")
        lines.append("|---|---|---|")
        for r in off["results"]:
            lines.append(f"| {r['name']} | {'PASS' if r['ok'] else 'FAIL'} | {r.get('detail') or '—'} |")
        lines.append("")
        lines.append("This is the proof behind the headline claim: install once, then airplane mode. "
                     "The worker lives at the repo root because a worker under `shell/` cannot "
                     "intercept `/games/` requests — the first version of this repo had exactly that "
                     "bug, and the test caught it.\n")

    lines.append("## Port artifacts on disk\n")
    lines.append("| title | artifact | bytes | sha256 (first 32) |")
    lines.append("|---|---|---|---|")
    for g in cat["games"]:
        if g["lane"] != "port":
            continue
        lines.append(f"| {g['title']} | `{os.path.basename(g.get('artifact') or '')}` | "
                     f"{g.get('artifact_bytes') or 0:,} | `{(g.get('artifact_sha256') or '—')[:32]}` |")
    lines.append("")
    lines.append("The six ports' *engines and assets* live outside this repository — the source tree "
                 "is ~18 GB and only the built artifacts are tracked. `ports/manifest.json` is the "
                 "map; each `ports/<id>/PROVENANCE.md` is the human-readable version, regenerated from "
                 "disk so the hashes cannot drift. What the originals reuse *is* vendored: see "
                 "`vendor/MANIFEST.json` and the section above.\n")

    lines.append(f"_Written {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}._\n")

    with open(OUT, "w") as f:
        f.write("\n".join(lines))
    print(f"wrote {OUT} ({rep['pass']}/{rep['total']} passing)")
    return 0 if rep["pass"] == rep["total"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
