#!/usr/bin/env node
/* Regenerates shell/lib/catalog.data.js from catalog/games.json so the shell
 * works from file:// (no fetch) while keeping one source of truth.
 * Usage: node tools/sync-catalog.mjs [--check] */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = join(root, 'catalog/games.json');
const out = join(root, 'shell/lib/catalog.data.js');
const raw = readFileSync(src, 'utf8');
const data = JSON.parse(raw);

const body = `/* GENERATED by tools/sync-catalog.mjs — do not edit by hand.
 * Source: catalog/games.json (${data.games.length} titles, updated ${data.updated}) */
window.AOMG_CATALOG = ${JSON.stringify(data, null, 1)};
`;

if (process.argv.includes('--check')) {
  let cur = '';
  try { cur = readFileSync(out, 'utf8'); } catch { }
  if (cur !== body) { console.error('catalog.data.js is stale — run: node tools/sync-catalog.mjs'); process.exit(1); }
  console.log('catalog.data.js in sync (' + data.games.length + ' games)');
  process.exit(0);
}
writeFileSync(out, body);
console.log('wrote', out, '(' + data.games.length + ' games,', body.length, 'bytes)');
